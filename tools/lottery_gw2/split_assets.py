"""Package the generated plate and existing GW2 controls as separate UI assets."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'design_refs/lottery_gw2_v1'
OUT = ROOT / 'art/ui/sources/custom_game/lottery_gw2_v1'
MIRROR = ROOT / 'panorama/src/images/custom_game/lottery_gw2_v1'
COLLECTION = ROOT / 'art/ui/sources/custom_game/collection_gw2_v1'
for folder in (OUT, MIRROR, REF / 'work'):
    folder.mkdir(parents=True, exist_ok=True)
assets = {}
resample = Image.Resampling.LANCZOS

def save(key, source, size, usage):
    image = Image.open(source).convert('RGBA').resize(size, resample)
    file = OUT / (key + '.png')
    image.save(file, optimize=True)
    data = file.read_bytes()
    (MIRROR / file.name).write_bytes(data)
    assets[key] = dict(file=file.relative_to(ROOT).as_posix(), size=list(size),
                      sha256=hashlib.sha256(data).hexdigest(),
                      source=source.relative_to(ROOT).as_posix(), usage=usage)

save('window_background', REF / 'blank_plate.png', (1536, 864), 'Generated text-free wide painterly perimeter plate.')
controls = {
    'header_strip': ('header_strip', (1456, 74)),
    'sidebar_background': ('sidebar_background', (276, 669)),
    'footer_strip': ('footer_strip', (1113, 70)),
    'tab_background': ('draw_button', (250, 104)),
    'tab_selected': ('draw_button', (250, 104)),
    'draw_button': ('draw_button', (240, 60)),
    'draw_button_hover': ('draw_button', (240, 60)),
    'slot_background': ('slot_background', (120, 120)),
    'slot_frame': ('slot_frame', (144, 170)),
    'slot_selected': ('slot_selected', (144, 170)),
    'close': ('close', (40, 40)),
    'scroll_track': ('scroll_track', (12, 320)),
    'scroll_thumb': ('scroll_thumb', (12, 100)),
    'tooltip_background': ('tooltip_background', (400, 280)),
    'tooltip_frame': ('tooltip_frame', (400, 280)),
}
for key, (source, size) in controls.items():
    save(key, COLLECTION / (source + '.png'), size,
         'Existing Collection GW2 bitmap control, packaged at lottery runtime size; no baked business values.')
manifest = dict(version=1, canvas=[1536, 864],
                reference='User-supplied Octopath Traveler gacha composition with existing GW2 Collection material style.',
                material_source='design_refs/lottery_gw2_v1/blank_plate.png',
                source_policy='Built-in imagegen blank plate; existing GW2 controls reused; four scene cards and all reward art remain authoritative existing assets.',
                assets=assets)
(Path(__file__).parent / 'asset_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
runtime = {key: dict(file='file://{images}/custom_game/lottery_gw2_v1/' + key + '.png', size=value['size'])
           for key, value in assets.items()}
(ROOT / 'panorama/src/scripts/custom_game/lottery_gw2_data.js').write_text(
    '// Generated by tools/lottery_gw2/split_assets.py; presentation assets only.\n'
    + '(function(){GameUI.CustomUIConfig().LotteryGW2Data='
    + json.dumps(dict(version=1, canvas=[1536, 864], assets=runtime), separators=(',', ':'))
    + ';})();\n', encoding='utf-8')
xml = '<root>\n  <Panel hittest="false" hittestchildren="false">\n'
for key, value in runtime.items():
    xml += '    <Image id="LotteryGW2Preload_' + key + '" src="' + value['file'] + '" visible="false" hittest="false" style="visibility:collapse; width:0px; height:0px;" />\n'
xml += '  </Panel>\n</root>\n'
(ROOT / 'panorama/src/layout/custom_game/lottery_gw2_assets.xml').write_text(xml, encoding='utf-8')
sheet = Image.new('RGB', (1200, 800), '#22292e')
draw = ImageDraw.Draw(sheet)
try:
    font = ImageFont.truetype('C:/Windows/Fonts/consola.ttf', 17)
except OSError:
    font = ImageFont.load_default()
for index, (key, entry) in enumerate(assets.items()):
    image = Image.open(ROOT / entry['file']).convert('RGBA')
    image.thumbnail((280, 145), resample)
    x, y = index % 4 * 300, index // 4 * 200
    sheet.paste(image, (x + (300 - image.width) // 2, y + 40), image)
    draw.text((x + 10, y + 10), key, fill='#e3ded2', font=font)
sheet.save(REF / 'work/components.png')
print('LOTTERY_GW2_COMPONENTS_READY', len(assets))
