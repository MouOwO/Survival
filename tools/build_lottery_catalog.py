"""Build the account-free lottery seed from the game's immutable server bundle."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import shutil
import sys


def generate(root: Path, lua: str, bundle_path: Path | None = None):
    sys.path.insert(0, str(root))
    from server.archive_backend.bundle import Bundle
    from server.archive_backend.lottery_catalog import catalog_document

    if bundle_path is None:
        declaration = (root / "scripts/vscripts/config/generated/archive_http_bundle.lua").read_text(encoding="utf-8-sig")
        match = re.search(r'\bhash\s*=\s*"([0-9a-f]{64})"', declaration)
        if not match:
            raise ValueError("lottery_seed_bundle_missing")
        bundle_path = root / "server/bundles" / match[1]
    document = catalog_document(Bundle(bundle_path), lua)
    seed = {"md5": document["catalog_md5"], "config_hash": document["config_hash"],
            "catalog_json": document["catalog_json"]}
    raw = json.dumps(seed, ensure_ascii=True, sort_keys=True, separators=(",", ":"))
    script = ("// AUTO-GENERATED by tools/build_lottery_catalog.py; public presentation only.\n"
              "(function(){GameUI.CustomUIConfig().SurvivalLotteryCatalogSeed=" + raw + ";})();\n")
    data = json.dumps(seed, ensure_ascii=True, indent=2) + "\n"
    manifest = ("-- AUTO-GENERATED by tools/build_lottery_catalog.py; presentation digest only.\n"
                'return { catalog_md5 = "' + seed["md5"] + '", config_hash = "' + seed["config_hash"] + '" }\n')
    files = {"panorama/src/scripts/custom_game/lottery_catalog_seed.js": script,
             "data/ui/lottery_catalog.json": data,
             "scripts/vscripts/config/generated/lottery_catalog_manifest.lua": manifest}
    return files, {"catalog_md5": seed["md5"], "config_hash": seed["config_hash"],
                   "pools": len(document["catalog"]["snapshots"]), "catalog_bytes": len(seed["catalog_json"])}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--bundle", type=Path)
    parser.add_argument("--lua", default=shutil.which("lua5.1") or shutil.which("lua") or r"C:\Program Files\lua\bin\lua5.1.exe")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    files, metadata = generate(root, args.lua, args.bundle)
    mismatches = []
    for relative, text in files.items():
        path = root / relative
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8-sig") != text:
                mismatches.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
    if mismatches:
        raise SystemExit("LOTTERY_CATALOG_STALE: " + ", ".join(mismatches))
    print(json.dumps({"status": "LOTTERY_CATALOG_CHECK_PASS" if args.check else "LOTTERY_CATALOG_BUILT", **metadata}))


if __name__ == "__main__":
    main()
