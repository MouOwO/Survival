"""Offline generator + real formal-birth integration. Never runs Dota."""
from pathlib import Path
import contextlib, copy, csv, io, json, shutil, subprocess, tempfile
import sync_wave_unit_names as sync
from build_wave_monster_cosmetics import parse_kv

ROOT = Path(__file__).resolve().parents[1]
LUA = r'C:\Program Files\lua\bin\lua5.1.exe'
CHECKPOINT = ROOT / 'output/four_operation_extreme_20261012/native_range_checkpoint_20261013_034050_268'

def lua(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + json.dumps(k) + ']=' + lua(v) for k, v in value.items()) + '}'
    if isinstance(value, bool): return 'true' if value else 'false'
    return json.dumps(value, ensure_ascii=False)

def main():
    before = parse_kv((CHECKPOINT/'scripts/npc/npc_units_custom.txt').read_text(encoding='utf-8-sig'))['DOTAUnits']
    current = parse_kv((ROOT/'scripts/npc/npc_units_custom.txt').read_text(encoding='utf-8-sig'))['DOTAUnits']
    aliases = {k: v for k, v in current.items() if k not in before}
    assert len(aliases) == 19
    for name, fields in before.items(): assert current[name] == fields, 'original NPC changed: ' + name
    def table(name):
        path=ROOT/'data/csv/怪物与波次系统'/name
        return list(csv.DictReader(line for line in path.read_text(encoding='utf-8-sig').splitlines() if line and not line.startswith('#')))
    archetypes={r['archetype_id']:r for r in table('monster_archetypes.csv')}
    for name,fields in aliases.items():
        identity=name.removeprefix('npc_survival_range_'); row=archetypes[identity]
        expected=copy.deepcopy(before[row['unit_name']]);expected['AttackRange']=str(int(float(row['attack_range'])))
        assert fields==expected, 'alias delta exceeds native range: '+name
    preserved=['data/csv/怪物与波次系统/monster_archetypes.csv', 'data/csv/怪物与波次系统/wave_definitions.csv',
               'scripts/vscripts/config/generated/monster_archetypes.lua','scripts/vscripts/config/generated/wave_definitions.lua']
    for path in preserved: assert (ROOT/path).read_bytes()==(CHECKPOINT/path).read_bytes(), 'shared source changed: '+path
    for path in ['resource/addon_schinese.txt','resource/localization/addon_schinese.txt']:
        old=parse_kv((CHECKPOINT/path).read_text(encoding='utf-8-sig'))['lang']['Tokens']
        now=parse_kv((ROOT/path).read_text(encoding='utf-8-sig'))['lang']['Tokens']
        for name,value in old.items():assert now[name]==value,'original locale changed: '+name
        for name in aliases: assert now[name]==archetypes[name.removeprefix('npc_survival_range_')]['display_name']
    with tempfile.TemporaryDirectory(prefix='survival_native_range_') as directory:
        temp=Path(directory)
        files=['scripts/npc/npc_units_custom.txt','resource/addon_schinese.txt','resource/localization/addon_schinese.txt']+preserved
        for relative in files:
            target=temp/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(CHECKPOINT/relative,target)
        previous=sync.ROOT;sync.ROOT=temp
        try:
            with contextlib.redirect_stdout(io.StringIO()): assert sync.sync_native_range_aliases()==19
            outputs=files[:3]+['scripts/vscripts/config/generated/wave_native_range_aliases.lua']
            first={f:(temp/f).read_bytes() for f in outputs}
            with contextlib.redirect_stdout(io.StringIO()): assert sync.sync_native_range_aliases()==19
            for f in outputs:assert (temp/f).read_bytes()==first[f],'rebuild not idempotent: '+f
            for f in preserved:assert (temp/f).read_bytes()==(CHECKPOINT/f).read_bytes()
            rebuilt=parse_kv((temp/files[0]).read_text(encoding='utf-8-sig'))['DOTAUnits']
            assert rebuilt==current
        finally: sync.ROOT=previous
        fixture=temp/'actual_native_unit_kv.lua';fixture.write_text('return '+lua(current)+'\n',encoding='utf-8')
        subprocess.run([LUA,str(ROOT/'tools/test_wave_native_range.lua'),str(fixture)],cwd=ROOT,check=True)
        old_helper=ROOT/'output/four_operation_extreme_20261012/native_range_precache_arity_checkpoint_20261013_042247_642/scripts/vscripts/systems/wave_native_attack_range.lua'
        negative=subprocess.run([LUA,str(ROOT/'tools/test_wave_native_range.lua'),str(fixture),str(old_helper)],
                                cwd=ROOT,text=True,capture_output=True)
        assert negative.returncode!=0 and 'expected19_arityfailures=19' in negative.stderr, 'strict native fixture failed to identify old two-argument precache'
        print('NATIVE_PRECACHE_ARITY_PASS current explicit(name,callback,-1); old actual helper two-argument negative control rejected before alias-ready admission')
    print('WAVE_NATIVE_RANGE_GENERATOR_PASS 19 single-field aliases; all old NPC/locale values and CSV/generated bytes preserved; 44 metadata contracts; idempotent generation')

if __name__=='__main__':main()
