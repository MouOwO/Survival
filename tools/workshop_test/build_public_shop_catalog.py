"""Generate a public, read-only shop from the formal compilers. No account or order IO."""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
sys.dont_write_bytecode = True
sys.path.insert(0, str(ROOT / "server"))
from payment_backend.csv_catalog import build, canonical
from payment_backend.commerce_bundles import compile_commerce

PUBLIC_BASE = "https://pay.xiaofengnet.com/ws4-shop/"
NATIVE = Path("panorama/src/scripts/custom_game/arcade_shop_catalog.js")
CONTENT = ROOT.parents[2] / "content/dota_addons/Survival"
CONTENT_SOURCE = Path("panorama/scripts/custom_game/arcade_shop_catalog.js")


def project(payment, commerce, payment_hash):
    """Keep offers distinct by channel; do not invent account eligibility or cash conversion."""
    offers = []
    for channel, rows in (("cash", payment["products"]), ("wallet", commerce["products"])):
        for product in rows:
            if product["enabled"] is not True:
                continue
            currency = "CNY" if channel == "cash" else product["currency"]
            price = product["amount"] if channel == "cash" else product["price"]
            if currency not in ("CNY", "u_coin", "shop_points", "shop_gold"):
                raise ValueError("public_shop_currency_invalid")
            if type(price) is not int or price <= 0:
                raise ValueError("public_shop_price_invalid")
            # Deliberately omit grants, effects, ownership markers and account state.
            offers.append(dict(
                offer_id=channel + ":" + product["sku"], sku=product["sku"],
                title=product["title"], description=product["description"],
                category_id=product["category_id"], product_type=product["product_type"],
                currency=currency, price=price, purchase_limit=product["purchase_limit"],
                required_vip_level=product["grants"].get("required_vip_level", 0),
                reward_lines=copy.deepcopy(product["grants"]["lines"])))
    ids = [item["offer_id"] for item in offers]
    if len(ids) != len(set(ids)):
        raise ValueError("public_shop_duplicate_offer")
    offers.sort(key=lambda item: (item["price"] / 100 if item["currency"] == "CNY"
                                 else item["price"], item["offer_id"]))
    data = dict(schema_version=1, checkout_enabled=False, availability="preview_only",
                source="payment_backend.csv_catalog.build+commerce_bundles.compile_commerce",
                payment_catalog_sha256=payment_hash,
                commerce_catalog_sha256=hashlib.sha256(canonical(commerce)).hexdigest(),
                categories=[dict(id=row["id"], label=row["label"]) for row in payment["categories"]],
                products=offers)
    data["catalog_sha256"] = hashlib.sha256(canonical(data)).hexdigest()
    return data


def catalog(root=ROOT):
    compiled = build(root)
    reference = {name: (Path(root) / "data/csv" / name).read_text(encoding="utf-8-sig")
                 for name in compiled["reference_hashes"]}
    commerce = compile_commerce(compiled["commerce_tables"], reference,
                                compiled["tables"]["payment_categories"])
    return project(compiled["catalog"], commerce, compiled["catalog_hash"])


def javascript(data, target):
    # Escape HTML-sensitive characters too, so later embedding never closes a script tag.
    text = canonical(data).decode().replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    text = text.replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    assignment = ("GameUI.CustomUIConfig().SurvivalArcadeShopCatalog" if target == "panorama"
                  else "window.SurvivalPublicShop")
    return ("// Generated by tools/workshop_test/build_public_shop_catalog.py; display only.\r\n"
            + assignment + " = " + text + ";\r\n").encode("utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="Write only the generated Panorama data file")
    parser.add_argument("--mirror-content", action="store_true")
    parser.add_argument("--web-output", type=Path, help="New output directory for the static, read-only website")
    args = parser.parse_args()
    if args.mirror_content and not args.write:
        parser.error("--mirror-content requires --write")
    data = catalog()
    native = javascript(data, "panorama")
    if args.write:
        (ROOT / NATIVE).write_bytes(native)
        if args.mirror_content:
            (CONTENT / CONTENT_SOURCE).write_bytes(native)
    if args.web_output:
        destination = args.web_output.resolve()
        if destination.exists():
            raise ValueError("new_web_output_required")
        destination.mkdir(parents=True)
        source = ROOT / "server/web_shop"
        files = {name: (source / name).read_bytes() for name in ("index.html", "shop.css", "shop.js")}
        files["catalog.js"] = javascript(data, "browser")
        files["catalog.json"] = canonical(data) + b"\n"
        for name, raw in files.items():
            (destination / name).write_bytes(raw)
        manifest = dict(schema_version=1, public_base=PUBLIC_BASE, checkout_enabled=False,
                        catalog_sha256=data["catalog_sha256"],
                        files={name: hashlib.sha256(raw).hexdigest() for name, raw in sorted(files.items())})
        (destination / "manifest.json").write_bytes(canonical(manifest) + b"\n")
    print(json.dumps(dict(ok=True, public_base=PUBLIC_BASE, checkout_enabled=False,
                         offers=len(data["products"]), cash_offers=sum(p["currency"] == "CNY" for p in data["products"]),
                         catalog_sha256=data["catalog_sha256"],
                         native_matches=(ROOT / NATIVE).is_file() and (ROOT / NATIVE).read_bytes() == native,
                         files_written=args.write or bool(args.web_output)), ensure_ascii=False))


if __name__ == "__main__":
    main()
