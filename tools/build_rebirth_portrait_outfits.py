"""Generate ten portrait outfits from world CSVs and installed Valve item slots."""
import argparse
import json
import re
from pathlib import Path

from build_unit_portraits import ENGINE, ROOT, Vpk, parse_kv, rows


def build():
    vpk = Vpk(ENGINE / 'game/dota/pak01_dir.vpk')
    schema = parse_kv(vpk.read('scripts/items/items_game.txt').decode('utf-8'))['items_game']
    assets = {row['asset_id']: row for row in rows('asset_catalog.csv')}
    components = rows('asset_components.csv')
    outfits = {}

    def inherited(row, key, seen=None):
        if key in row:
            return row[key]
        seen = set() if seen is None else set(seen)
        for prefab in row.get('prefab', '').split():
            if prefab in seen:
                continue
            value = inherited(schema['prefabs'].get(prefab, {}), key, seen | {prefab})
            if value is not None:
                return value
        return None

    bosses = [row for row in rows('monster_archetypes.csv')
              if re.fullmatch(r'rebirth_boss_(0[1-9]|10)', row.get('archetype_id', ''))]
    assert len(bosses) == 10
    for boss in bosses:
        asset_id = boss['default_wearable_asset_id']
        asset = assets[asset_id]
        source_unit = asset['portrait_unit_name']
        hero_name = {'npc_dota_hero_doom': 'npc_dota_hero_doom_bringer'}.get(source_unit, source_unit)
        hero = parse_kv(vpk.read(f'scripts/npc/heroes/{hero_name}.txt').decode('utf-8'))['DOTAHeroes'][hero_name]
        slots = {entry['SlotName']: int(entry['SlotIndex']) for entry in hero['ItemSlots'].values()}
        items = []
        for component in components:
            if component['asset_id'] != asset_id or component.get('enabled') != '1':
                continue
            match = re.search(r'ItemDef\s+(\d+)', component['notes'])
            assert match, f'Missing item identity: {component["component_key"]}'
            item_def = match[1]
            item = schema['items'][item_def]
            assert inherited(item, 'model_player') == component['model_path'], component['component_key']
            assert inherited(item, 'used_by_heroes').get(hero_name) == '1', item_def
            slot = inherited(item, 'item_slot')
            assert slot in slots, f'Unknown {hero_name} slot: {slot}'
            # These ten world outfits use the default item style. Reject a future
            # skin edit rather than silently preview a different cosmetic style.
            assert component.get('model_skin', '') in ('', '0')
            items.append([slots[slot], int(item_def), 0])
        assert items and len({item[0] for item in items}) == len(items), asset_id
        outfits[asset_id] = {'unit': hero_name, 'source_unit': source_unit, 'items': sorted(items)}
    return '// Generated by tools/build_rebirth_portrait_outfits.py; Valve slots, world CSV items.\n' + \
        '(function () { GameUI.CustomUIConfig().SurvivalRebirthPortraitOutfits = ' + \
        json.dumps(outfits, ensure_ascii=False, indent=2) + '; })();\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'panorama/src/scripts/custom_game/rebirth_portrait_outfits.js'
    source = build()
    if args.check:
        assert output.read_text(encoding='utf-8') == source, 'Portrait outfits need regeneration'
        print('REBIRTH_PORTRAIT_OUTFITS_CHECK_PASS: ten CSV outfits, exact Valve hero slots and item models')
    else:
        output.write_text(source, encoding='utf-8')
        print('Generated ten rebirth portrait outfits')


if __name__ == '__main__':
    main()
