"""Slice the approved Collection shell/atlas into independent runtime material."""
from pathlib import Path
import json
import hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[2]
REF=ROOT/'design_refs/collection_gw2_v1'
OUT=ROOT/'art/ui/sources/custom_game/collection_gw2_v1'
MIRROR=ROOT/'panorama/src/images/custom_game/collection_gw2_v1'
TOOLS=Path(__file__).resolve().parent
for folder in (OUT,MIRROR,REF/'work'): folder.mkdir(parents=True,exist_ok=True)
plate=Image.open(REF/'blank_plate.png').convert('RGBA')
atlas=Image.open(REF/'control_atlas.png').convert('RGBA')
resample=Image.Resampling.LANCZOS
normalized=plate.resize((1200,800),resample)
assets={}

def save(key,im,source,crop,usage):
    dest=OUT/(key+'.png'); im.convert('RGBA').save(dest,optimize=True)
    content=dest.read_bytes(); (MIRROR/dest.name).write_bytes(content)
    assets[key]=dict(file=dest.relative_to(ROOT).as_posix(),size=list(im.size),
                     sha256=hashlib.sha256(content).hexdigest(),source=source,crop=crop,usage=usage)

def substrate(key,box,size,usage):
    save(key,normalized.crop(box).resize(size,resample),'blank_plate.png / 1200x800',list(box),usage)

save('window_background',normalized.resize((1160,744),resample),'blank_plate.png',None,'Text-free shell; no slots or baked UI values.')
substrate('header_strip',(29,25,1173,86),(1160,74),'Independent empty title band.')
substrate('sidebar_background',(29,87,88,699),(112,598),'Blank category rail, with no old bag menu.')
substrate('footer_strip',(88,701,1173,771),(1016,86),'Empty draw/currency band; real values remain live.')
substrate('tab_background',(35,128,82,192),(98,104),'Unselected category background.')

keys=['slot_frame','slot_hover','slot_selected','slot_background',
      'tab_ex','tab_friend','tab_wife','tab_selected',
      'draw_button','draw_button_hover','close','collection_icon',
      'scroll_track','scroll_thumb','tooltip_background','tooltip_frame']
custom={'draw_button':(.02,.548,.25,.673),
        'scroll_track':(.105,.715,.165,.965),
        'scroll_thumb':(.26,.765,.312,.915),
        'tooltip_background':(.382,.75,.69,.925),
        'tooltip_frame':(.702,.75,.978,.925)}
images={}
for i,key in enumerate(keys):
    col,row=i%4,i//4
    if key in custom:
        x0,y0,x1,y1=custom[key]
        box=tuple(round(v*d) for v,d in zip((x0,y0,x1,y1),(atlas.width,atlas.height,atlas.width,atlas.height)))
    else:
        box=(round(col*atlas.width/4)+12,round(row*atlas.height/4)+12,
             round((col+1)*atlas.width/4)-12,round((row+1)*atlas.height/4)-12)
    im=atlas.crop(box)
    # Ignore nearly invisible alpha dust when isolating actual controls.
    bbox=im.getchannel('A').point(lambda a:255 if a>32 else 0).getbbox()
    assert bbox, 'Missing component '+key
    im=im.crop(bbox)
    if key.startswith('slot_') or key=='tab_selected': im=im.resize((72,72) if key.startswith('slot_') else (98,104),resample)
    elif key.startswith('tab_') or key in ('close','collection_icon'): im.thumbnail((80,80),resample)
    elif key.startswith('draw_button'): im=im.resize((240,44),resample)
    elif key.startswith('scroll_'): im=im.resize((12,320 if key=='scroll_track' else 100),resample)
    elif key.startswith('tooltip_'): im=im.resize((360,240),resample)
    images[key]=im
    save(key,im,'control_atlas.png',list(box),'Isolated live UI component; no player data or example loot.')
save('search_background',images['tooltip_background'].resize((287,35),resample),'control_atlas.png / tooltip background',None,'Text-free search-field backing.')

manifest=dict(version=1,canvas=[1200,800],reference='User-supplied marked Guild Wars 2 Inventory screenshot',
              material_source='design_refs/collection_gw2_v1/blank_plate.png',
              source_policy='Imagegen text-free shell and atlas, deterministically isolated; portraits, count and draw state use authoritative game data.',assets=assets)
(TOOLS/'asset_manifest.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
runtime={k:dict(file='file://{images}/custom_game/collection_gw2_v1/'+k+'.png',size=v['size']) for k,v in assets.items()}
(ROOT/'panorama/src/scripts/custom_game/collection_gw2_data.js').write_text(
    '// Generated by tools/collection_gw2/split_assets.py; art only.\n(function(){GameUI.CustomUIConfig().CollectionGW2Data='+json.dumps(dict(version=1,canvas=[1200,800],assets=runtime),separators=(',',':'))+';})();\n',encoding='utf-8')
xml='<root>\n  <Panel hittest="false" hittestchildren="false">\n'
for k,v in runtime.items():
    xml+='    <Image id="CollectionGW2Preload_'+k+'" src="'+v['file']+'" visible="false" hittest="false" style="visibility:collapse; width:0px; height:0px;" />\n'
xml+='  </Panel>\n</root>\n'
(ROOT/'panorama/src/layout/custom_game/collection_gw2_assets.xml').write_text(xml,encoding='utf-8')

sheet=Image.new('RGB',(1200,((len(assets)+3)//4)*200),'#22292e')
draw=ImageDraw.Draw(sheet)
try: font=ImageFont.truetype('C:/Windows/Fonts/consola.ttf',17)
except OSError: font=ImageFont.load_default()
for i,(key,entry) in enumerate(assets.items()):
    im=Image.open(ROOT/entry['file']).convert('RGBA'); im.thumbnail((280,145),resample)
    x,y=(i%4)*300,(i//4)*200; sheet.paste(im,(x+(300-im.width)//2,y+40),im)
    draw.text((x+10,y+10),key,fill='#e3ded2',font=font)
sheet.save(REF/'work/components.png')
print('COLLECTION_GW2_COMPONENTS_READY',len(assets))
