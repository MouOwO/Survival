        challenges = [shadow_challenge, "social_friend"]
        if difficulty >= 5: challenges.insert(1, "hunt_01")
        if difficulty >= 7: challenges.insert(1, "cage_1")
        self.accounts = [10000 + seed * 10 + i for i in range(4)]
        self.session = f"rewardstress{scene}{number}seed{seed}"
        self.db = LocalDatabase(self.bundle)
        self.app = fixture_module.App(self.db)
        self.service = ArchiveService(self.app, self.bundle, LUA)
        self.current = {"scene": scene, "round": number, "seed": seed, "session": self.session,
                        "checks": 0, "bugs": [], "snapshots": {}, "transport": [],
                        "oracle": {}, "local_synthetic_accounts": self.accounts, "difficulty": "N" + str(difficulty),
                        "shadow_challenge": shadow_challenge, "challenges": challenges}
        self.rounds.append(self.current)
        levels = [[1, 9, 17, 24], [3, 12, 20, 30], [7, 16, 28, 34], [8, 18, 25, 32], [10, 19, 26, 33]][number - 1]
