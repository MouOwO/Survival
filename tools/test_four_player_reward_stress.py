def json_container_semantics(value, path=()):
    # Only schema-defined map fields accept Lua's [] spelling of an empty map.
    # Unknown fields, missing values, arrays and sequences retain their type.
    typed_map = path in MAP_PATHS or (len(path) == 3 and path[:2] == ("archive", "daily"))
    if value == [] and typed_map:
        return {}
    if isinstance(value, dict):
        return {key: json_container_semantics(child, path + (key,)) for key, child in value.items()}
    return value


class LocalDatabase(fixture_module.Database):
    """Extend the existing local test DB to honor expiry and deterministic date.

    This models the production RPC's prepared personal monthly entitlement;
    it does not access a real database or emulate the reward reducer.
    """
    def rpc(self, name, payload):
        if name == "archive_prepare":
            account = payload["p_account"]
            entitlement = self.profile(account)["entitlements"].get("archive_pass", {})
            active = entitlement.get("active") is True and entitlement.get("expires_at", NOW + 1) > NOW
            result = super().rpc(name, payload)
            op = self.ops[(account, payload["p_id"])]
            if not op["done"]:
                op["pass"] = active
            return self.resume(account, payload["p_id"])
        return super().rpc(name, payload)


class Controller:
    def __init__(self, bundle):
        self.bundle, self.rounds, self.current = bundle, [], None

    def check(self, value, message, actual=None, expected=None):
        self.current["checks"] += 1
        if not value:
            self.current["bugs"].append({"check": message, "actual": actual, "expected": expected})

    def snapshot(self, player):
        profile = copy.deepcopy(self.db.profile(self.app._database_account_id(str(self.accounts[player]))))
        profile["account_id"] = str(self.accounts[player])
        profile["match_session_id"], profile["mode"] = self.session, "standard"
        profile["progression"] = {"loaded": True, "clear_counts": profile["save"]["archive"].get("clear_counts", {})}
        return profile

