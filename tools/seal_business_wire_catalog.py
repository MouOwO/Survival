"""Encrypt public wire-schema JSON into a signed-release Lua table module.

ChaCha20 is encrypted local storage, not confidentiality from the player: the
module includes its read key. Release signatures provide authenticity. Never
store server secrets here. Decode JSON data only, never execute the plaintext.

Generation/check is offline O(B), B <= 256 KiB. --check never changes ciphertext
or keys. Every generation uses independent random key/nonce. Receipts live in
the explicit external local-tools directory, never in the mounted addon.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import sys

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / 'server/player_web_auth/business_wire_schema.json'
OUTPUT = ROOT / 'scripts/vscripts/config/generated/business_wire_catalog.lua'
EXTERNAL = Path('D:/Survival_本地工具')
MAX_BYTES = 256 * 1024
FORMAT = re.compile(
    r"\A-- AUTO-GENERATED PUBLIC CONFIGURATION; ChaCha20 encrypted local storage\.\n"
    r"-- The local read key is public; release signatures provide authenticity\.\n"
    r"return require\('core/local_config_cipher'\)\.catalog\(\n"
    r"    '([0-9a-f]*)',\n    '([0-9a-f]{64})',\n"
    r"    '([0-9a-f]{24})',\n    '([0-9a-f]{64})'\n\)\n\Z"
)


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':'), allow_nan=False).encode('utf-8')


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def pairs(items):
    result = {}
    for key, value in items:
        if key in result:
            raise ValueError('duplicate_json_key')
        result[key] = value
    return result


def material():
    raw = SCHEMA.read_bytes()
    if len(raw) > MAX_BYTES:
        raise ValueError('schema_size_exceeded')
    schema = json.loads(raw, object_pairs_hook=pairs, parse_constant=lambda _: (_ for _ in ()).throw(ValueError('nonfinite_json')))
    if type(schema) is not dict:
        raise ValueError('schema_object_required')
    schema_raw = canonical(schema)
    fingerprint = sha(schema_raw)
    plaintext = canonical({'hash': fingerprint, 'schema': schema})
    if len(plaintext) > MAX_BYTES:
        raise ValueError('catalog_size_exceeded')
    return schema_raw, fingerprint, plaintext


def crypt(raw, key, nonce):
    # RFC 8439 counter=1 + 96-bit nonce. cryptography's 128-bit state input has
    # exactly these state bytes. Bounded files never carry into a nonce word.
    cipher = Cipher(algorithms.ChaCha20(key, (1).to_bytes(4, 'little') + nonce), mode=None)
    return cipher.encryptor().update(raw)


def render(ciphertext, key, nonce, fingerprint):
    return ("-- AUTO-GENERATED PUBLIC CONFIGURATION; ChaCha20 encrypted local storage.\n"
            "-- The local read key is public; release signatures provide authenticity.\n"
            "return require('core/local_config_cipher').catalog(\n"
            f"    '{ciphertext.hex()}',\n    '{key.hex()}',\n"
            f"    '{nonce.hex()}',\n    '{fingerprint}'\n)\n").encode('ascii')


def verify(raw, plaintext, fingerprint):
    # Git's Lua attributes may materialize CRLF in the working tree. The
    # committed producer emits LF; ciphertext/key/nonce bytes remain exact.
    matched = FORMAT.fullmatch(raw.replace(b'\r\n', b'\n').decode('ascii'))
    if not matched:
        raise ValueError('generated_catalog_format_invalid')
    encrypted, key, nonce, stated_hash = matched.groups()
    encrypted = bytes.fromhex(encrypted)
    if len(encrypted) > MAX_BYTES or stated_hash != fingerprint:
        raise ValueError('generated_catalog_source_mismatch')
    actual = crypt(encrypted, bytes.fromhex(key), bytes.fromhex(nonce))
    if actual != plaintext:
        raise ValueError('generated_catalog_roundtrip_mismatch')
    return encrypted


def receipt_path(value):
    path = Path(value)
    if not path.is_absolute() or not path.resolve().is_relative_to(EXTERNAL.resolve()):
        raise ValueError('receipt_must_be_in_external_local_tools')
    if path.exists():
        raise ValueError('immutable_receipt_already_exists')
    return path


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Read-only: decrypt and compare existing generated bytes.')
    parser.add_argument('--replace', action='store_true', help='Explicitly replace an existing generated module with a new key/nonce.')
    parser.add_argument('--receipt', required=True, help='New JSON receipt below D:/Survival_本地工具.')
    options = parser.parse_args(argv)
    receipt = receipt_path(options.receipt)
    schema_raw, fingerprint, plaintext = material()
    if options.check:
        if options.replace:
            raise ValueError('check_cannot_replace')
        raw = OUTPUT.read_bytes()
        ciphertext = verify(raw, plaintext, fingerprint)
    else:
        if OUTPUT.exists() and not options.replace:
            raise ValueError('catalog_exists_use_check_or_explicit_replace')
        key, nonce = os.urandom(32), os.urandom(12)
        ciphertext = crypt(plaintext, key, nonce)
        raw = render(ciphertext, key, nonce, fingerprint)
        verify(raw, plaintext, fingerprint)
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        if options.replace:
            OUTPUT.write_bytes(raw)
        else:
            with OUTPUT.open('xb') as stream:
                stream.write(raw)
    result = {
        'kind': 'BUSINESS_WIRE_ENCRYPTED_CATALOG_RECEIPT',
        'status': 'CHECKED' if options.check else 'GENERATED',
        'observed_at_utc': datetime.now(timezone.utc).isoformat(),
        'artifact_root': str(receipt.parent.resolve()),
        'source_root': str(ROOT.resolve()),
        'schema_path': str(SCHEMA.resolve()),
        'catalog_path': str(OUTPUT.resolve()),
        'schema_sha256': fingerprint,
        'schema_bytes': len(schema_raw),
        'plaintext_sha256': sha(plaintext),
        'plaintext_bytes': len(plaintext),
        'ciphertext_sha256': sha(ciphertext),
        'ciphertext_bytes': len(ciphertext),
        'catalog_sha256': sha(raw),
        'catalog_bytes': len(raw),
        'cipher': 'RFC8439_CHACHA20_COUNTER1',
        'key_is_local_readable': True,
        'confidentiality_from_client_claimed': False,
        'runtime_plaintext_execution': False,
        'roundtrip_exact': True,
        'release_signature_required': True,
        'changed_existing_ciphertext': bool(options.replace and not options.check),
    }
    receipt.parent.mkdir(parents=True, exist_ok=True)
    with receipt.open('x', encoding='utf-8', newline='\n') as stream:
        json.dump(result, stream, ensure_ascii=False, indent=2)
        stream.write('\n')
    print(json.dumps(result, ensure_ascii=False))
    return 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (ValueError, OSError, UnicodeError) as error:
        print(json.dumps({'ok': False, 'error': str(error)}, ensure_ascii=False), file=sys.stderr)
        raise SystemExit(2)
