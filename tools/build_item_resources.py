def lua(value):
    if isinstance(value, str):
        # Lua 5.1 supports the ASCII escapes used here; UTF-8 remains literal.
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, bool):
        return 'true' if value else 'false'
    if isinstance(value, (int, float)):
        return str(value)
    if isinstance(value, list):
        return '{' + ','.join(lua(v) for v in value) + '}'
    if isinstance(value, dict):
        return '{' + ','.join('[' + lua(k) + ']=' + lua(v) for k, v in value.items()) + '}'
    raise TypeError(type(value).__name__)


def load(root=ROOT):
    path = root / SOURCE
    source = json.loads(path.read_bytes())
    assert source['schema_version'] == 1 and isinstance(source['items'], list), 'resource_schema'
    rows, aliases = {}, {}
    for row in source['items']:
        identity = row['id']
        assert re.fullmatch(r'[A-Za-z0-9_:.-]{1,160}', identity), 'resource_id:' + identity
        assert identity not in rows, 'duplicate_resource:' + identity
        uri = row['uri']
        assert re.fullmatch(r'(?:file://\{images\}/|s2r://panorama/images/)[A-Za-z0-9_/-]+\.(?:png|svg|vtex)', uri), 'resource_uri:' + identity
        assert row['kind'] in {'image', 'hero', 'vip', 'tier_badge', 'layered_title', 'endless_emblem'}, 'resource_kind:' + identity
        assert isinstance(row.get('aliases'), list), 'resource_aliases:' + identity
        if 'fit' in row:
            assert row['fit'] in ('contain', 'cover'), 'resource_fit:' + identity
        if row['kind'] == 'vip':
            assert type(row['vip_level']) is int and 1 <= row['vip_level'] <= 12, 'vip_resource_level'
        if row['kind'] == 'hero':
            assert re.fullmatch(r'npc_dota_hero_[a-z0-9_]+', row['hero_name']), 'hero_resource_name'
        if row['kind'] == 'tier_badge':
            assert re.fullmatch(r'(?:LV|V)[1-9][0-9]?', row['badge_text']), 'tier_badge_text:' + identity
            assert re.fullmatch(r'#[0-9a-fA-F]{6}', row['badge_color']), 'tier_badge_color:' + identity
            if row.get('overlay_uri'):
                assert re.fullmatch(r's2r://panorama/images/rank_tier_icons/pip[1-7]_psd\.vtex', row['overlay_uri']), 'tier_badge_overlay:' + identity
        rows[identity] = row
    for identity, row in rows.items():
        for alias in [identity, *row['aliases']]:
            assert isinstance(alias, str) and re.fullmatch(r'[A-Za-z0-9_:.-]{1,160}', alias), 'invalid_alias'
            assert alias not in aliases or aliases[alias] == identity, 'ambiguous_alias:' + alias
            aliases[alias] = identity
    return source, rows, aliases


def lookup(item, root=ROOT):
    _, rows, aliases = load(root)
    keys = [item] if isinstance(item, str) else [item.get(key) for key in (
        'resource_id', 'sku', 'item_id', 'content_id', 'contentid', 'id', 'ownership_id',
        'entry_id', 'entryid', 'shop_entry_id', 'source_id', 'reward_id', 'card_id')]
    return next((rows[aliases[key]] for key in keys if isinstance(key, str) and key in aliases), None)


def item_art_adapter(source):
    # Keep the legacy factory and family fallback, replacing its embedded data
    # and lookup function. Known resources always return through the registry.
    match = re.search(r'\bentries\s*=\s*', source)
    assert match, 'legacy_item_art_anchor'
    _, count = json.JSONDecoder().raw_decode(source[match.end():])
    source = source[:match.end()] + '[]' + source[match.end()+count:]
    start = source.index('    function lookup(item){')
    end = source.index('    // Approved original atlases;', start)
    replacement = '''    function lookup(item){
        var row=cfg.SurvivalItemResources&&cfg.SurvivalItemResources.Lookup(item);
        return row?{item_id:row.id,content_id:row.id,runtime_uri:row.uri,icon_path:row.uri,
            display_name:row.name,kind:row.kind,vip_level:row.vip_level,quality:row.quality,
            category_id:row.category_id}:null;
    }
'''
    return (source[:start] + replacement + source[end:]).replace(
        'SetScaling(\'stretch-to-fit-preserve-aspect\')', 'SetScaling(\'stretch-to-cover-preserve-aspect\')')


def icons_adapter(source):
    match = re.search(r'\bentries\s*=\s*', source)
    assert match, 'legacy_icons_anchor'
    if source[match.end():].startswith('['):
        _, count = json.JSONDecoder().raw_decode(source[match.end():])
        expression = '''(cfg.SurvivalItemResources?cfg.SurvivalItemResources.Rows():[]).map(function(row){
        return {item_id:row.id,category_id:row.category_id||"items",display_name:row.name,
            runtime_uri:row.uri,display_width:84,display_height:84};
    })'''
        source = source[:match.end()] + expression + source[match.end()+count:]
    else:
        assert source[match.end():].startswith('(cfg.SurvivalItemResources?'), 'icons_adapter_changed'
    return source


def runtime_rows(source):
    return [{k: v for k, v in row.items() if k in ('id', 'name', 'kind', 'uri', 'aliases',
        'native_name', 'native_type', 'vip_level', 'hero_name', 'source_size', 'quality', 'category_id',
        'badge_text', 'badge_color', 'overlay_uri', 'fit')} for row in source['items']]


def build(root=ROOT, check=False):
    source, rows, aliases = load(root)
    digest = hashlib.sha256((root / SOURCE).read_bytes()).hexdigest()
    runtime = runtime_rows(source)
    name_path = root / DISPLAY_NAMES
    names = json.loads(name_path.read_bytes()) if name_path.is_file() else {}
    display_names, offer_names, text_aliases = (names.get(key, {}) for key in ('names','offer_names','aliases'))
    for table in (display_names, offer_names, text_aliases):
        assert isinstance(table, dict) and all(isinstance(k,str) and isinstance(v,str) for k,v in table.items()), 'display_names_schema'
    # Short and ambiguous character names need stable IDs. Embedded prose only
    # gets unambiguous long aliases, once, so replacements cannot cascade.
    pattern = '|'.join(re.escape(key) for key in sorted(text_aliases, key=lambda value:(-len(value),value))
                       if len(key) >= 4 and key != text_aliases[key]) or '(?!)'
    name_hash = hashlib.sha256(name_path.read_bytes()).hexdigest() if name_path.is_file() else ''
    js = JS_TEMPLATE.replace('@HASH@', digest).replace('@ROWS@', json.dumps(runtime, ensure_ascii=False, separators=(',', ':')))
    for marker,value in [('@NAME_HASH@',name_hash),('@DISPLAY_NAMES@',json.dumps(display_names,ensure_ascii=False,separators=(',',':'))),
                         ('@OFFER_NAMES@',json.dumps(offer_names,ensure_ascii=False,separators=(',',':'))),
                         ('@TEXT_ALIASES@',json.dumps(text_aliases,ensure_ascii=False,separators=(',',':'))),
                         ('@TEXT_PATTERN@',json.dumps(pattern,ensure_ascii=False))]:
        js=js.replace(marker,value)
    lua_source = '-- AUTO-GENERATED by tools/build_item_resources.py from ' + SOURCE + '\n'
    lua_source += 'local M = { source_hash = ' + lua(digest) + ', rows = {\n'
    lua_source += ''.join('    ' + lua(row) + ',\n' for row in runtime) + '} }\n'
    lua_source += '''M.by_id = {}
for _,row in ipairs(M.rows) do
    M.by_id[row.id] = row
    for _,id in ipairs(row.aliases) do M.by_id[id] = row end
end
function M.lookup(item)
    if type(item)=="string" then return M.by_id[item] end
    if type(item)~="table" then return nil end
    for _,key in ipairs({"resource_id","sku","item_id","content_id","contentid","id","ownership_id",
        "entry_id","entryid","shop_entry_id","source_id","reward_id","card_id"}) do
        local row=M.by_id[item[key]];if row then return row end
    end
end
return M
'''
    art_file = 'panorama/src/scripts/custom_game/item_art_remaining_5d5c1152eb.js'
    outputs = {JS: js, LUA: lua_source,
        'panorama/src/scripts/custom_game/native_ui_icons.js': NATIVE_ADAPTER,
        'panorama/src/scripts/custom_game/archive_v10_icons.js': ARCHIVE_ADAPTER,
        art_file: item_art_adapter((root / art_file).read_text(encoding='utf-8-sig')),
        'panorama/src/scripts/custom_game/icons_remaining_5d5c1152eb.js': icons_adapter(
            (root / 'panorama/src/scripts/custom_game/icons_remaining_5d5c1152eb.js').read_text(encoding='utf-8-sig'))}
    for name, text in outputs.items():
        target = root / name
        if check:
            assert target.is_file() and target.read_text(encoding='utf-8-sig') == text, 'resource_output_stale:' + name
        elif not target.exists() or target.read_text(encoding='utf-8-sig') != text:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8', newline='\n')
    return {'status': 'CHECK_PASS' if check else 'GENERATED', 'items': len(rows), 'aliases': len(aliases),
            'source': SOURCE, 'source_sha256': digest, 'display_names_source':DISPLAY_NAMES,
            'display_names_sha256':name_hash, 'outputs': list(outputs)}


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    print(json.dumps(build(check=args.check), ensure_ascii=False))
