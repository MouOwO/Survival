"""Package imagegen's login materials into independent, text-free components."""
from pathlib import Path
import hashlib
import json
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[2]
REF = ROOT / 'design_refs/daily_gw2_v1'
OUT = ROOT / 'art/ui/sources/custom_game/daily_gw2_v1'
MIRROR = ROOT / 'panorama/src/images/custom_game/daily_gw2_v1'
TOOLS = Path(__file__).resolve().parent
for folder in (OUT, MIRROR, REF / 'work'):
    folder.mkdir(parents=True, exist_ok=True)
plate = Image.open(REF / 'blank_plate.png').convert('RGBA')
atlas = Image.open(REF / 'control_atlas.png').convert('RGBA')
grey_atlas = Image.open(REF / 'grey_frames_atlas.png').convert('RGBA')
resample = Image.Resampling.LANCZOS
assets = {}

def save(key, im, source, crop, usage):
    dest = OUT / (key + '.png')
    im.convert('RGBA').save(dest, optimize=True)
    payload = dest.read_bytes()
    (MIRROR / dest.name).write_bytes(payload)
    assets[key] = dict(file=dest.relative_to(ROOT).as_posix(), size=list(im.size),
                       sha256=hashlib.sha256(payload).hexdigest(), source=source,
                       crop=crop, usage=usage)

def plate_crop(key, box, size, usage):
    save(key, plate.crop(box).resize(size, resample), 'blank_plate.png', list(box), usage)

# The source model kept the crown separate above its title ribbon and empty body.
assert plate.size == (1448, 1086), 'Review new plate geometry before changing crop coordinates.'
plate_crop('crown', (0, 0, 1448, 305), (1060, 182), 'Gold crown and crescents; no text or reward values.')
plate_crop('title_brush', (0, 296, 1448, 387), (1164, 61), 'Independent blue-black painted title ribbon.')
plate_crop('window_background', (0, 384, 1448, 1086), (1164, 703), 'Empty smoky reward-panel material, with transparent rough perimeter.')

keys = ['reward_frame', 'reward_frame_hover', 'reward_frame_today', 'reward_frame_claimed',
        'premium_frame', 'premium_frame_locked', 'selection_glow', 'divider',
        'button', 'button_hover', 'close', 'lock',
        'check', 'tooltip_background', 'tooltip_frame', 'premium_emblem']
for index, key in enumerate(keys):
    source_atlas = grey_atlas if key in ('reward_frame', 'reward_frame_hover') else atlas
    source_name = 'grey_frames_atlas.png' if source_atlas is grey_atlas else 'control_atlas.png'
    col, row = index % 4, index // 4
    x0, y0 = round(col * source_atlas.width / 4), round(row * source_atlas.height / 4)
    x1, y1 = round((col + 1) * source_atlas.width / 4), round((row + 1) * source_atlas.height / 4)
    # Only isolate this requested component; the atlas is never a runtime UI.
    box = (x0 + 14, y0 + 14, x1 - 14, y1 - 14)
    tile = source_atlas.crop(box)
    # Imagegen leaves nearly invisible alpha outside controls. Crop against
    # visible paint rather than counting those pixels as the control's size.
    bbox = tile.getchannel('A').point(lambda value: 255 if value > 32 else 0).getbbox()
    assert bbox, f'Missing component: {key}'
    tile = tile.crop(bbox)
    if key in ('reward_frame_today', 'selection_glow'):
        # Remove residual paint from the transparent center during isolation.
        alpha = tile.getchannel('A')
        inset = .24
        ImageDraw.Draw(alpha).rectangle((round(tile.width*inset), round(tile.height*inset),
                                        round(tile.width*(1-inset)), round(tile.height*(1-inset))), fill=0)
        tile.putalpha(alpha)
    if key == 'divider':
        tile = tile.transpose(Image.Transpose.ROTATE_90).resize((12, 485), resample)
    elif key.startswith(('reward_frame', 'premium_frame')) or key == 'selection_glow':
        tile = tile.resize((120, 120), resample)
    elif key in ('button', 'button_hover'):
        tile = tile.resize((248, 46), resample)
    elif key in ('close', 'lock', 'check', 'premium_emblem'):
        tile.thumbnail((64, 64), resample)
    elif key.startswith('tooltip_'):
        tile = tile.resize((350, 240), resample)
    save(key, tile, source_name, list(box), 'Isolated live UI control; no reward data or quantities.')

manifest = dict(version=1, canvas=[1200,900], reference='User-supplied Guild Wars 2 Login Rewards screenshot',
                material_source='design_refs/daily_gw2_v1/blank_plate.png',
                source_policy='Imagegen text-free material and control atlas; all reward icons, numbers and eligibility remain live.',
                assets=assets)
(TOOLS / 'asset_manifest.json').write_text(json.dumps(manifest, indent=2)+'\n', encoding='utf-8')
runtime = {key: dict(file='file://{images}/custom_game/daily_gw2_v1/'+key+'.png',size=entry['size']) for key,entry in assets.items()}
data = dict(version=1,canvas=[1200,900],assets=runtime)
(ROOT / 'panorama/src/scripts/custom_game/daily_gw2_data.js').write_text(
    '// Generated by tools/daily_gw2/split_assets.py; art only.\n(function(){GameUI.CustomUIConfig().DailyGW2Data='+json.dumps(data,separators=(',',':'))+';})();\n', encoding='utf-8')
xml = '<root>\n  <Panel hittest="false" hittestchildren="false">\n'
for key, entry in runtime.items():
    xml += '    <Image id="DailyGW2Preload_'+key+'" src="'+entry['file']+'" visible="false" hittest="false" style="visibility:collapse; width:0px; height:0px;" />\n'
xml += '  </Panel>\n</root>\n'
(ROOT / 'panorama/src/layout/custom_game/daily_gw2_assets.xml').write_text(xml,encoding='utf-8')

sheet = Image.new('RGB',(1200,((len(assets)+3)//4)*210),'#222b31')
draw = ImageDraw.Draw(sheet)
try: font=ImageFont.truetype('C:/Windows/Fonts/consola.ttf',17)
except OSError: font=ImageFont.load_default()
for i,(key,entry) in enumerate(assets.items()):
    im=Image.open(ROOT/entry['file']).convert('RGBA'); im.thumbnail((280,160),resample)
    x,y=(i%4)*300,(i//4)*210
    sheet.paste(im,(x+(300-im.width)//2,y+40),im)
    draw.text((x+10,y+10),key,fill='#e5e0d3',font=font)
sheet.save(REF/'work/components.png')
print('DAILY_GW2_COMPONENTS_READY',len(assets))
