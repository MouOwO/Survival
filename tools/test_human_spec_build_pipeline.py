"""Exercise the real CSV main and dual-document importer in temporary copies.

The required visual/rogue/rich CSVs are copied as a valid subset; validation,
generation and human-spec importing run normally. Only the
unrelated final model/localization name sync is suppressed. Production generated
files are never rebuilt or modified by this suite.
"""
from __future__ import annotations

import contextlib
import importlib.util
import io
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest
from unittest import mock

import openpyxl

ROOT = Path(__file__).resolve().parents[1]


class HumanSpecBuildPipelineTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory(prefix="human_spec_build_")
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        shutil.copytree(ROOT / "data/balance/human_spec_v3",
                        self.root / "data/balance/human_spec_v3",
                        copy_function=shutil.copyfile)
        csv_names = {
            "enums.csv", "rogue_reward_cards.csv", "rogue_reward_effects.csv",
            "rogue_reward_effect_params.csv", "rogue_reward_effect_lifecycle.csv",
            "rich_wave_definitions.csv", "rich_wave_stat_variants.csv",
            "rich_challenge_combat_profiles.csv", "monster_visual_assets.csv",
            "monster_visual_components.csv", "monster_visual_effects.csv",
            "wave_visual_definitions.csv",
        }
        for path in (ROOT / "data/csv").rglob("*.csv"):
            if path.name in csv_names:
                destination = self.root / path.relative_to(ROOT)
                destination.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(path, destination)
        (self.root / "data/csv/pipeline_probe.csv").write_text(
            "id,value\n#types:string,number\nprobe,7\n", encoding="utf-8")
        for relative in (
            "tools/build_configs.py", "tools/build_rich_configs.py",
            "tools/import_human_monster_spec.py",
            "scripts/vscripts/config/human_monster_rules.lua",
        ):
            destination = self.root / relative
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ROOT / relative, destination)
        self.source = self.root / "data/balance/human_spec_v3"
        self.output = self.root / "scripts/vscripts/config/generated"
        self.output.mkdir(parents=True)
        self.spec_path = self.output / "human_monster_spec.lua"
        for name in ("human_monster_spec.lua", "index.lua", "orphan_old_config.lua",
                     "pipeline_probe.lua", "building_white_shells.lua"):
            (self.output / name).write_text("-- existing " + name + "\n", encoding="utf-8")
        (self.source / "normalized.json").write_text('{"existing": true}\n', encoding="utf-8")
        module_spec = importlib.util.spec_from_file_location(
            "human_spec_fixture_builder", self.root / "tools/build_configs.py")
        self.builder = importlib.util.module_from_spec(module_spec)
        module_spec.loader.exec_module(self.builder)

    def snapshot(self):
        return {str(path.relative_to(self.root)): path.read_bytes()
                for path in [*self.output.rglob("*"), self.source / "normalized.json"]
                if path.is_file()}

    def run_main(self):
        original_run = subprocess.run

        def run(command, **kwargs):
            if Path(command[1]).name == "sync_wave_unit_names.py":
                return subprocess.CompletedProcess(command, 0)
            # The real importer is a separate process rooted in the fixture.
            return original_run(command, capture_output=True, text=True,
                                encoding="utf-8", env={**os.environ, "PYTHONUTF8": "1"},
                                **kwargs)

        with mock.patch.object(self.builder.subprocess, "run", side_effect=run), \
                contextlib.redirect_stdout(io.StringIO()):
            return self.builder.main()

    def test_rebuild_regenerates_spec_preserves_it_and_cleans_orphans(self):
        self.assertEqual(self.run_main(), 0)
        first = self.spec_path.read_bytes()
        self.assertIn(b"Generated by tools/import_human_monster_spec.py", first)
        self.assertFalse((self.output / "orphan_old_config.lua").exists())
        self.assertIn(b"value = 7", (self.output / "pipeline_probe.lua").read_bytes())
        self.assertEqual((self.output / "building_white_shells.lua").read_text(encoding="utf-8"),
                         "-- existing building_white_shells.lua\n")

        # Wave bases exist only in the workbook. A normal CSV rebuild must
        # import its changed value rather than merely keep stale Lua alive.
        workbook_path = self.source / "接入规格_人话版_v3.xlsx"
        workbook = openpyxl.load_workbook(workbook_path)
        workbook["波次小怪基础值"].cell(9, 3).value = 4123.5
        workbook.save(workbook_path)
        workbook.close()
        self.assertEqual(self.run_main(), 0)
        self.assertNotEqual(self.spec_path.read_bytes(), first)
        normalized = json.loads((self.source / "normalized.json").read_text(encoding="utf-8"))
        self.assertEqual(normalized["waves"]["8"]["health"], 4123.5)
        self.assertIn(b'["health"] = 4123.5', self.spec_path.read_bytes())

    def test_conflicting_sources_fail_before_existing_outputs_change(self):
        json_path = self.source / "human_spec.json"
        document = json.loads(json_path.read_text(encoding="utf-8-sig"))
        document["modes"][0]["HP倍率"] = 999
        json_path.write_text(json.dumps(document, ensure_ascii=False), encoding="utf-8")
        before = self.snapshot()
        with self.assertRaises(subprocess.CalledProcessError) as raised:
            self.run_main()
        self.assertIn("Conflicting sources", raised.exception.stderr)
        self.assertEqual(self.snapshot(), before)

    def test_each_required_input_is_checked_before_outputs_change(self):
        for relative in ("tools/import_human_monster_spec.py",
                         "data/balance/human_spec_v3/human_spec.json",
                         "data/balance/human_spec_v3/接入规格_人话版_v3.xlsx"):
            with self.subTest(relative=relative):
                path = self.root / relative
                saved = path.read_bytes()
                path.unlink()
                before = self.snapshot()
                try:
                    with self.assertRaisesRegex(ValueError, "specification inputs missing"):
                        self.run_main()
                    self.assertEqual(self.snapshot(), before)
                finally:
                    path.write_bytes(saved)

    def test_older_fixture_without_human_consumer_keeps_csv_pipeline(self):
        (self.root / "scripts/vscripts/config/human_monster_rules.lua").unlink()
        (self.root / "tools/import_human_monster_spec.py").unlink()
        self.assertEqual(self.run_main(), 0)
        self.assertFalse(self.spec_path.exists())
        self.assertFalse((self.output / "orphan_old_config.lua").exists())
        self.assertTrue((self.output / "pipeline_probe.lua").is_file())


if __name__ == "__main__":
    unittest.main()
