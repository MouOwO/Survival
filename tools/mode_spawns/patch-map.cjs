// Patch a current Hammer snapshot, preserving unrelated hand edits. Installation
// and compilation are explicit separate steps; no template regeneration occurs.
'use strict';
const fs = require('node:fs'), path = require('node:path'), crypto = require('node:crypto');
const L = require('../map_c6/lib.cjs'), Mesh = require('../map_c6/mesh.cjs');
const root = path.resolve(__dirname, '../..');
const arg = key => { const i = process.argv.indexOf(key); return i < 0 ? null : process.argv[i + 1]; };
const assert = (condition, message) => { if (!condition) throw Error(message); };
const sha = data => crypto.createHash('sha256').update(data).digest('hex');
const layoutPath = path.resolve(arg('--layout') || path.join(root, 'art/maps/mode_spawns/layout.json'));
const layout = JSON.parse(fs.readFileSync(layoutPath, 'utf8'));
assert(layout.schema_version === 1, 'Unsupported layout');
const inside = (b, p, margin = 0) => p[0] >= b[0] + margin && p[0] <= b[2] - margin
    && p[1] >= b[1] + margin && p[1] <= b[3] - margin;
const bounds = b => `{ min_x = ${b[0]}, min_y = ${b[1]}, max_x = ${b[2]}, max_y = ${b[3]} }`;
const names = new Set(), markers = [];
let config = '-- Generated by tools/mode_spawns/patch-map.cjs from art/maps/mode_spawns/layout.json.\n'
    + '-- Hammer info_target entities are authoritative; these rectangles bound construction.\n'
    + `return {\n    map_name = "${layout.map_name}",\n    modes = {\n`;
for (const mode of ['rich', 'cold', 'scourge']) {
    const row = layout.modes[mode];
    assert(row.players.length === 4 && row.monsters.length === 4 && row.player_bounds.length === 4, mode + ': expected four slots');
    for (const b of [row.bounds, ...row.player_bounds]) {
        assert(b.length === 4 && b.every(v => Number.isFinite(v) && v % 64 === 0)
            && b[0] < b[2] && b[1] < b[3], 'Invalid aligned bounds: ' + mode);
    }
    const add = (name, origin, role) => {
        assert(!names.has(name) && origin.length === 3 && origin.every(Number.isFinite), 'Invalid marker ' + name);
        assert(inside(row.bounds, origin), 'Marker outside mode: ' + name);
        names.add(name); markers.push({name, origin: [origin[0], origin[1], origin[2] + 16], role});
    };
    add(mode + '_start', row.center, 'center');
    config += `        ${mode} = {\n            center_marker = "${mode}_start",\n            bounds = ${bounds(row.bounds)},\n`;
    for (const [kind, positions] of [['player', row.players], ['monster', row.monsters]]) {
        config += `            ${kind}_markers = {\n`;
        positions.forEach((p, id) => {
            if (kind === 'player') {
                assert(inside(row.player_bounds[id], p, 32), 'Player needs a complete grid cell: ' + mode + id);
                assert(inside(row.bounds, row.player_bounds[id].slice(0, 2))
                    && inside(row.bounds, row.player_bounds[id].slice(2)), 'Lawn outside mode');
                for (let other = 0; other < id; other++) {
                    const a = row.player_bounds[id], b = row.player_bounds[other];
                    assert(a[2] <= b[0] || b[2] <= a[0] || a[3] <= b[1] || b[3] <= a[1], 'Overlapping player lawns');
                }
            }
            const name = `mode_${mode}_${kind}_${id}_spawn`;
            add(name, p, kind + ':' + id);
            config += `                [${id}] = "${name}",\n`;
        });
        config += '            },\n';
    }
    config += '            player_bounds = {\n';
    row.player_bounds.forEach((b, id) => { config += `                [${id}] = ${bounds(b)},\n`; });
    config += '            },\n        },\n';
}
config += '    },\n}\n';
const configPath = path.resolve(arg('--config') || path.join(root, 'scripts/vscripts/config/mode_spawn_config.lua'));
fs.mkdirSync(path.dirname(configPath), {recursive: true});
fs.writeFileSync(configPath, config);
if (process.argv.includes('--config-only')) { console.log('MODE_SPAWN_CONFIG_OK ' + configPath); process.exit(0); }
assert(arg('--source') && arg('--out'), 'Usage: node tools/mode_spawns/patch-map.cjs --source current-text.vmap --out patched.vmap [--report report.json]');
const sourcePath = path.resolve(arg('--source')), outputPath = path.resolve(arg('--out'));
assert(sourcePath !== outputPath, 'Output must not overwrite the input snapshot');
const source = fs.readFileSync(sourcePath, 'utf8');
assert(source.slice(0, 100).includes('encoding keyvalues2'), 'Convert the current binary snapshot with dmxconvert -oe keyvalues2 first');
const entities = L.blocks(source, 'CMapEntity');
let nextNode = Math.max(...[...source.matchAll(/"nodeID" "int" "(\d+)"/g)].map(m => +m[1])) + 1;
const edits = [], additions = [], changedMarkers = [];
const sourceMeshes = L.blocks(source, 'CMapMesh'), rampNodes = [];
for (const ramp of layout.ramps || []) {
    assert(ramp.mode === 'cold' && ramp.width >= 256 && ramp.lip >= 64, 'Invalid mode approach');
    const [a, b] = [ramp.start, ramp.end], length = Math.hypot(b[0] - a[0], b[1] - a[1]);
    assert(length > 0 && Math.abs(b[2] - a[2]) / length <= 0.5, 'Approach too steep');
    const dx = (b[0] - a[0]) / length, dy = (b[1] - a[1]) / length;
    const cross = [-dy * ramp.width / 2, dx * ramp.width / 2];
    const before = [a[0] - dx * ramp.lip, a[1] - dy * ramp.lip, a[2]];
    const after = [b[0] + dx * ramp.lip, b[1] + dy * ramp.lip, b[2]];
    const edge = p => [[p[0] - cross[0], p[1] - cross[1], p[2]], [p[0] + cross[0], p[1] + cross[1], p[2]]];
    const pairs = [before, a, b, after].map(edge), quads = [];
    for (let i = 0; i < pairs.length - 1; i++) quads.push([pairs[i][0], pairs[i + 1][0], pairs[i + 1][1], pairs[i][1]]);
    const old = sourceMeshes.filter(m => m.text.includes('"name" "string" "' + ramp.name + '"'));
    assert(old.length <= 1, 'Duplicate approach ' + ramp.name);
    const nodeID = old.length ? +L.value(old[0].text, 'nodeID') : nextNode++;
    const mesh = Mesh.mesh(quads, ramp.material, nodeID, () => ({blend: [1, 0, 0, 0.4], tint: [0.9, 0.95, 1, 0.03]}));
    const namedMesh = mesh.replace(/("nodeID" "int" "\d+")/, '$1\n"name" "string" "' + ramp.name + '"');
    if (old.length) edits.push({...old[0], text: namedMesh}); else additions.push(namedMesh);
    rampNodes.push({name: ramp.name, nodeID, start: a, end: b, width: ramp.width});
}
for (const marker of markers) {
    const existing = entities.filter(b => L.value(b.text, 'targetname') === marker.name);
    assert(existing.length <= 1, 'Duplicate existing marker: ' + marker.name);
    const origin = marker.origin.join(' ');
    if (existing.length) {
        const b = existing[0];
        assert(['info_target', 'info_player_start_dota'].includes(L.value(b.text, 'classname')), 'Marker class changed: ' + marker.name);
        edits.push({...b, text: L.setValue(L.setValue(b.text, 'origin', origin), 'classname', 'info_target')});
        changedMarkers.push({...marker, nodeID: +L.value(b.text, 'nodeID'), action: 'updated'});
    } else {
        const nodeID = nextNode++, uid = () => crypto.randomUUID();
        additions.push(`"CMapEntity" { "id" "elementid" "${uid()}" "nodeID" "int" "${nodeID}"\n`
            + `"children" "element_array" [] "entity_properties" "EditGameClassProps" { "id" "elementid" "${uid()}" `
            + `"classname" "string" "info_target" "targetname" "string" "${marker.name}" }\n`
            + `"origin" "vector3" "${origin}" "angles" "qangle" "0 0 0" "scales" "vector3" "1 1 1" `
            + '"force_hidden" "bool" "0" "editorOnly" "bool" "0" }');
        changedMarkers.push({...marker, nodeID, action: 'added'});
    }
}
const grid = L.blocks(source, 'CMapDotaTileGrid');
assert(grid.length === 1, 'Expected one native terrain');
const nav = L.array(grid[0].text, 'gridnavFlags'), water = L.array(grid[0].text, 'verticesWater');
assert(nav.length === 512 * 512 && water.length === 129 * 129, 'Unexpected native grid size');
const changedCells = [];
for (let y = 0; y < 512; y++) for (let x = 0; x < 512; x++) {
    const p = [-16352 + x * 64, -16352 + y * 64], index = y * 512 + x;
    if (nav[index] === '0' || !layout.rich_navigation.open_rectangles.some(b => inside(b, p))) continue;
    const tx = Math.floor(x / 4), ty = Math.floor(y / 4);
    // Open dry land only: a sea tile or shoreline never becomes a shortcut.
    if (![ty * 129 + tx, ty * 129 + tx + 1, (ty + 1) * 129 + tx, (ty + 1) * 129 + tx + 1].every(i => water[i] === '0')) continue;
    nav[index] = '0'; changedCells.push(index);
}
edits.push({...grid[0], text: L.setArray(grid[0].text, 'gridnavFlags', nav)});
edits.sort((a, b) => a.start - b.start);
let cursor = 0; const parts = [];
for (const edit of edits) { assert(edit.start >= cursor, 'Overlapping edits'); parts.push(source.slice(cursor, edit.start), edit.text); cursor = edit.end; }
parts.push(source.slice(cursor)); let result = parts.join('');
if (additions.length) {
    const world = result.indexOf('"world" "CMapWorld"'); assert(world >= 0, 'Missing world');
    const start = result.indexOf('[', result.indexOf('"children" "element_array"', world));
    const end = L.endOf(result, start, '[', ']') - 1;
    result = result.slice(0, end).replace(/,\s*$/, '') + ',\n' + additions.join(',\n') + '\n' + result.slice(end);
}
const after = L.blocks(result, 'CMapEntity');
for (const marker of markers) assert(after.filter(b => L.value(b.text, 'targetname') === marker.name).length === 1, 'Missing/duplicate ' + marker.name);
const unchanged = entities.filter(b => !names.has(L.value(b.text, 'targetname')));
const afterNodes = new Map(after.map(b => [L.value(b.text, 'nodeID'), b.text]));
for (const b of unchanged) assert(afterNodes.get(L.value(b.text, 'nodeID')) === b.text, 'Unrelated entity changed');
for (const b of sourceMeshes) {
    if (!rampNodes.some(r => r.nodeID === +L.value(b.text, 'nodeID'))) assert(result.includes(b.text), 'Unrelated mesh changed');
}
// Terrain is byte-identical apart from the bounded nav flag array.
const maskNav = text => text.replace(/("gridnavFlags" "\w+_array"\s*)\[[^\]]*\]/, '$1[]');
assert(maskNav(grid[0].text) === maskNav(L.blocks(result, 'CMapDotaTileGrid')[0].text), 'Terrain outside nav flags changed');
fs.mkdirSync(path.dirname(outputPath), {recursive: true}); fs.writeFileSync(outputPath, result);
const report = {source: sourcePath, source_sha256: sha(source), output: outputPath, output_sha256: sha(result),
    layout_sha256: sha(fs.readFileSync(layoutPath)), config_sha256: sha(config), markers: changedMarkers, approaches: rampNodes,
    changed_nav_cells: changedCells, preserved_entities: unchanged.length, preserved_meshes: L.blocks(source, 'CMapMesh').length,
    preserved_terrain_except_nav: true};
fs.writeFileSync(arg('--report') || outputPath + '.json', JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify({markers: markers.length, added: additions.length, changed_nav_cells: changedCells.length, preserved_entities: unchanged.length}));
