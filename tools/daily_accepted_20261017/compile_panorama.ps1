param([switch]$Isolated)
$ErrorActionPreference = 'Stop'
$addon = (Resolve-Path (Join-Path $PSScriptRoot '../..')).Path
$engine = [IO.Path]::GetFullPath((Join-Path $addon '../../..'))
$compiler = Join-Path $engine 'game/bin/win64/resourcecompiler.exe'
$sourcePrefix = if ($Isolated) { 'tmp/spp/panorama/src/' } else { 'panorama/src/' }
$backup = Join-Path $addon ('output/daily_accepted_compile/' + (Get-Date -Format yyyyMMdd_HHmmss_fff) + '_' + [guid]::NewGuid().ToString('N').Substring(0,8))
New-Item -ItemType Directory -Force -Path $backup | Out-Null
$records = @()
$succeeded = $false
$failure = $null
$restoreErrors = @()
function FileHash($path) {
    if (Test-Path -LiteralPath $path) { return (Get-FileHash -LiteralPath $path -Algorithm SHA256).Hash }
    return $null
}
function AssertHash($path, $expected, $stage) {
    if ((FileHash $path) -ne $expected) { throw "Concurrent write at $stage to $path; retained current file and backups in $backup" }
}
function SaveManifest {
    ConvertTo-Json -InputObject @($records) -Depth 8 |
        Set-Content -LiteralPath (Join-Path $backup 'manifest.json') -Encoding UTF8
    [pscustomobject]@{
        isolated = [bool]$Isolated; succeeded = $succeeded; failure = $failure
        backup = $backup; restoreErrors = $restoreErrors
    } | ConvertTo-Json -Depth 8 | Set-Content -LiteralPath (Join-Path $backup 'status.json') -Encoding UTF8
}
try {
    foreach ($item in @(
        @('scripts/custom_game/daily_gw2_data.js', 'scripts/custom_game/daily_gw2_data.vjs_c'),
        @('scripts/custom_game/daily_remaining_5d5c1152eb.js', 'scripts/custom_game/daily_remaining_5d5c1152eb.vjs_c'),
        @('styles/custom_game/daily_gw2.css', 'styles/custom_game/daily_gw2.vcss_c'),
        @('layout/custom_game/daily_gw2_assets.xml', 'layout/custom_game/daily_gw2_assets.vxml_c')
    )) {
        $index = $records.Count
        $source = Join-Path $addon ($sourcePrefix + $item[0])
        $content = Join-Path $engine ('content/dota_addons/Survival/panorama/' + $item[0])
        $runtime = Join-Path $addon ('panorama/' + $item[1])
        $isolatedRuntime = Join-Path $addon ('tmp/spp/panorama/' + $item[1])
        $record = [pscustomobject]@{
            source = $source; content = $content; runtime = $runtime; isolatedRuntime = $isolatedRuntime
            sourceHash = FileHash $source; contentBeforeHash = FileHash $content; runtimeBeforeHash = FileHash $runtime
            isolatedBeforeHash = FileHash $isolatedRuntime; compiledHash = $null
            sourceBackup = Join-Path $backup "$index.source"; contentBackup = Join-Path $backup "$index.content"
            runtimeBackup = Join-Path $backup "$index.runtime"; compiledBackup = Join-Path $backup "$index.compiled"
            compilerLog = Join-Path $backup "$index.compiler.log"
            contentOwnedHash = $null; runtimeOwnedHash = $null; runtimeAttempted = $false
            contentRestored = $false; runtimeRestored = $false
        }
        if (-not $record.sourceHash) { throw "Missing source: $source" }
        Copy-Item -LiteralPath $source -Destination $record.sourceBackup
        AssertHash $record.sourceBackup $record.sourceHash 'source snapshot'
        AssertHash $source $record.sourceHash 'source snapshot'
        foreach ($kind in @('runtime', 'content')) {
            $hash = $record.($kind + 'BeforeHash')
            if ($hash) {
                Copy-Item -LiteralPath $record.$kind -Destination $record.($kind + 'Backup')
                AssertHash $record.($kind + 'Backup') $hash "$kind snapshot"
            }
            AssertHash $record.$kind $hash "$kind snapshot"
        }
        $records += $record
    }
    SaveManifest
    foreach ($record in $records) {
        AssertHash $record.source $record.sourceHash 'before compile'
        AssertHash $record.content $record.contentBeforeHash 'before content write'
        AssertHash $record.runtime $record.runtimeBeforeHash 'before native compile'
        New-Item -ItemType Directory -Force -Path (Split-Path -Parent $record.content) | Out-Null
        Copy-Item -LiteralPath $record.sourceBackup -Destination $record.content -Force
        $record.contentOwnedHash = $record.sourceHash
        AssertHash $record.runtime $record.runtimeBeforeHash 'immediately before native compile'
        $started = (Get-Date).ToUniversalTime()
        $record.runtimeAttempted = $true
        $log = @(& $compiler -i $record.content -game (Join-Path $engine 'game/dota') -fshallow -nop4 2>&1)
        $code = $LASTEXITCODE
        $log | Set-Content -LiteralPath $record.compilerLog -Encoding UTF8
        # Snapshot compiler output even on failure so recovery guards the exact
        # file generated by this invocation instead of overwriting later writes.
        $record.runtimeOwnedHash = FileHash $record.runtime
        SaveManifest
        if ($code -ne 0 -or -not ($log -match '0 failed')) { throw "Native compile failed for $($record.source); see $($record.compilerLog)" }
        $built = Get-Item -LiteralPath $record.runtime
        if ($built.Length -le 0 -or $built.LastWriteTimeUtc -lt $started) { throw "Compiled resource is empty or stale: $($record.runtime)" }
        AssertHash $record.source $record.sourceHash 'after native compile'
        AssertHash $record.content $record.sourceHash 'after native compile'
        $record.compiledHash = $record.runtimeOwnedHash
        Copy-Item -LiteralPath $record.runtime -Destination $record.compiledBackup
        AssertHash $record.compiledBackup $record.compiledHash 'compiled snapshot'
        if ($Isolated) {
            AssertHash $record.isolatedRuntime $record.isolatedBeforeHash 'before isolated copy'
            New-Item -ItemType Directory -Force -Path (Split-Path -Parent $record.isolatedRuntime) | Out-Null
            Copy-Item -LiteralPath $record.compiledBackup -Destination $record.isolatedRuntime -Force
            AssertHash $record.isolatedRuntime $record.compiledHash 'after isolated copy'
        }
        SaveManifest
    }
    foreach ($record in $records) {
        AssertHash $record.source $record.sourceHash 'final source verification'
        AssertHash $record.content $record.sourceHash 'final content verification'
        AssertHash $record.runtime $record.compiledHash 'final native verification'
    }
    $succeeded = $true
} catch {
    $failure = $_.Exception.ToString()
} finally {
    if ($Isolated -or -not $succeeded) {
        foreach ($record in $records) {
            foreach ($kind in @('runtime', 'content')) {
                $ownedHash = $record.($kind + 'OwnedHash')
                if (-not $ownedHash -and -not ($kind -eq 'runtime' -and $record.runtimeAttempted)) { continue }
                try {
                    $target = $record.$kind
                    AssertHash $target $ownedHash "before $kind restore"
                    $beforeHash = $record.($kind + 'BeforeHash')
                    if ($beforeHash) {
                        $saved = $record.($kind + 'Backup')
                        AssertHash $saved $beforeHash "$kind backup verification"
                        Copy-Item -LiteralPath $saved -Destination $target -Force
                    } else {
                        Remove-Item -LiteralPath $target -Force
                    }
                    AssertHash $target $beforeHash "after $kind restore"
                    $record.($kind + 'Restored') = $true
                } catch { $restoreErrors += $_.Exception.Message }
            }
        }
    }
    SaveManifest
    Write-Output ('DAILY_ACCEPTED_NATIVE_REPORT ' + $backup)
}
if ($restoreErrors.Count) { throw ($restoreErrors -join [Environment]::NewLine) }
if ($failure) { throw $failure }
Write-Output 'DAILY_ACCEPTED_NATIVE_COMPILE_PASS'
