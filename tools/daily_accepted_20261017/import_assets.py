"""Import the reviewed daily reward components, without screenshot/text/icon layers.

--apply writes byte-identical selected PNGs, lossless texture recipes and UI data.
--check verifies the repository against the source package without changing it.
"""
from __future__ import annotations

import argparse
import importlib.util
import io
import json
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
spec = importlib.util.spec_from_file_location('shop_import_utils', ROOT / 'tools/shop_v10_20261017/import_assets.py')
utils = importlib.util.module_from_spec(spec)
spec.loader.exec_module(utils)
checked_child, sha256, json_bytes = utils.checked_child, utils.sha256, utils.json_bytes
DATA_RELATIVE = Path('data/ui/daily_accepted_layers.json')
FOLDER = 'daily_accepted_v1'
SELECTION = {
    'window_edge': 'window_brush_edge', 'header_rule': 'header_rule',
    'divider': 'monthly_divider', 'reward_frame': 'week_r1_c1_frame',
    'button': 'monthly_button_base', 'close_base': 'close_base',
    'close': 'close_cross', 'lock': 'monthly_1_lock', 'check': 'week_r1_c1_claimed',
}
REUSED = {'window_background': 'window_background.png',
          'tooltip_background': 'tooltip_background.png', 'tooltip_frame': 'tooltip_frame.png'}


def texture_recipe(layer_id: str) -> bytes:
    return utils.texture_recipe(layer_id).replace(b'shop_v10_v1', FOLDER.encode())


def generate(source: Path) -> dict[str, bytes]:
    manifest_raw = checked_child(source, 'manifest.json').read_bytes()
    manifest = json.loads(manifest_raw.decode('utf-8-sig'))
    assert manifest['ui_bounds'] == {'left': 46, 'top': 146, 'width': 1382, 'height': 784}
    layers = {layer['id']: layer for layer in manifest['layers']}
    assets, files = [], {}
    for key in [*SELECTION, *REUSED]:
        layer = layers[SELECTION[key]] if key in SELECTION else None
        origin = layer['path'] if layer else 'panorama/src/images/custom_game/daily_gw2_v1/' + REUSED[key]
        raw = checked_child(source if layer else ROOT, origin).read_bytes()
        with Image.open(io.BytesIO(raw)) as image:
            image.load()
            assert image.mode == 'RGBA', key
            width, height = image.size
        if layer:
            assert (width, height) == (layer['width'], layer['height'])
            assert layer['kind'] not in ('raster_text', 'game_context'), key
        destination = f'panorama/src/images/custom_game/{FOLDER}/{key}.png'
        recipe = f'panorama/src/images/custom_game/{FOLDER}/{key}_v10.vtex'
        runtime = f'panorama/images/custom_game/{FOLDER}/{key}_v10.vtex_c'
        uri = f's2r://panorama/images/custom_game/{FOLDER}/{key}_v10.vtex'
        recipe_raw = texture_recipe(key)
        files[destination], files[recipe] = raw, recipe_raw
        assets.append(dict(id=key, origin=origin, source_layer=layer['id'] if layer else None,
                           width=width, height=height, sha256=sha256(raw),
                           recipe_sha256=sha256(recipe_raw), destination=destination,
                           recipe=recipe, runtime=runtime, runtime_uri=uri))
    data = dict(version=2, canvas=[1382, 784],
                layout=dict(cellWidth=118, cellHeight=119, cellPadding=5,
                            columns=[62, 207, 355, 505, 652, 802, 952],
                            rows=[152, 293, 437, 582], monthlyX=1175),
                assets={asset['id']: dict(file=asset['runtime_uri'], size=[asset['width'], asset['height']]) for asset in assets})
    data['assets']['premium_frame'] = data['assets']['reward_frame']
    files[str(DATA_RELATIVE)] = json_bytes(dict(source_manifest_sha256=sha256(manifest_raw),
                                               source_canvas=manifest['canvas'], ui_bounds=manifest['ui_bounds'],
                                               assets=assets, excluded='All raster text, concept icons, quantities, composites and damaged inpainted bases.'))
    files['panorama/src/scripts/custom_game/daily_gw2_data.js'] = (
        '// Art/layout only. Generated by tools/daily_accepted_20261017/import_assets.py.\n'
        '(function(){GameUI.CustomUIConfig().DailyGW2Data=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';})();\n').encode()
    files['panorama/src/layout/custom_game/daily_gw2_assets.xml'] = (
        '<root>\n  <Panel hittest="false" hittestchildren="false">\n' + ''.join(
            '    <Image id="DailyGW2Preload_' + asset['id'] + '" src="' + asset['runtime_uri'] +
            '" visible="false" hittest="false" style="visibility:collapse; width:0px; height:0px;" />\n'
            for asset in assets) + '  </Panel>\n</root>\n').encode()
    return files


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, required=True)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument('--apply', action='store_true')
    mode.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate(args.source)
    for relative, raw in generated.items():
        target = checked_child(ROOT, relative)
        if args.apply:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
        elif not target.is_file() or target.read_bytes() != raw:
            raise ValueError('Generated file differs: ' + relative)
    print('DAILY_ACCEPTED_IMPORT_PASS ' + str(len(generated)) + ' files; 12 selected lossless assets')
