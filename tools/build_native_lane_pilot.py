"""Two inert Tools aliases: retain complete source KV and change only BaseClass.

Default --check never writes. --write adds one #base prefix and independent
generated files; it never projects CSV, names, localization, or wave logic.
"""
from __future__ import annotations

import argparse
import copy
import hashlib
import json
from pathlib import Path

from build_wave_monster_cosmetics import parse_kv

ROOT = Path(__file__).resolve().parents[1]
INCLUDE_NAME = 'npc_tools_native_lane_pilot.txt'
SPECS = ('humanoid_white_melee', 'dwarf_white_rifle')
OUTPUTS = ('scripts/npc/' + INCLUDE_NAME,
           'scripts/vscripts/config/generated/native_lane_pilot_manifest.lua')


def kv_text(value, indent=0):
    if isinstance(value, dict):
        return '{\n' + ''.join(' ' * (indent + 4) + json.dumps(k) + ' '
                                + kv_text(v, indent + 4) + '\n'
                                for k, v in value.items()) + ' ' * indent + '}'
    return json.dumps(value, ensure_ascii=False)


def lua_text(value):
    if isinstance(value, dict):
        return '{' + ','.join('[' + json.dumps(k) + ']=' + lua_text(v)
                              for k, v in value.items()) + '}'
    if isinstance(value, list):
        return '{' + ','.join(lua_text(v) for v in value) + '}'
    if isinstance(value, bool):
        return 'true' if value else 'false'
    return json.dumps(value, ensure_ascii=False)


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, ensure_ascii=True,
                                    separators=(',', ':')).encode()).hexdigest()


def without_include(raw):
    bom = b'\xef\xbb\xbf' if raw.startswith(b'\xef\xbb\xbf') else b''
    body = raw[len(bom):]
    for newline in (b'\r\n', b'\n'):
        prefix = ('#base "' + INCLUDE_NAME + '"').encode() + newline
        if body.startswith(prefix):
            assert INCLUDE_NAME.encode() not in body[len(prefix):], 'duplicate/unmanaged include'
            return bom + body[len(prefix):], bom + prefix
    assert INCLUDE_NAME.encode() not in body, 'unmanaged include position'
    newline = b'\r\n' if b'\r\n' in body else b'\n'
    return raw, bom + ('#base "' + INCLUDE_NAME + '"').encode() + newline


def build(root=ROOT):
    npc = root / 'scripts/npc/npc_units_custom.txt'
    raw = npc.read_bytes()
    original, prefix = without_include(raw)
    source = parse_kv(original.decode('utf-8-sig'))['DOTAUnits']
    aliases, manifest = {}, []
    for archetype in SPECS:
        name = 'npc_survival_wave_named_' + archetype
        alias = 'npc_survival_tools_lane_' + archetype
        assert alias not in source, 'alias collides with an existing unit'
        fields = source[name]
        assert fields['BaseClass'] == 'npc_dota_creature'
        assert fields['ConsideredHero'] == fields['HasInventory'] == '0'
        changed = copy.deepcopy(fields)
        changed['BaseClass'] = 'npc_dota_creep_lane'
        assert {k for k in set(fields) | set(changed)
                if fields.get(k) != changed.get(k)} == {'BaseClass'}
        aliases[alias] = changed
        manifest.append(dict(archetype_id=archetype, source_unit_name=name,
                             alias_unit_name=alias, source_fields=fields,
                             source_kv_sha256=digest(fields),
                             alias_kv_sha256=digest(changed)))
    text = '// Inert Tools loader definitions; not selected by production waves.\n'
    text += '"DOTAUnits" ' + kv_text(aliases) + '\n'
    assert parse_kv(text)['DOTAUnits'] == aliases
    values = dict(schema='native_lane_pilot_v1', alias_count=2, unit_budget=1,
                  formal_registration=False, rows=manifest)
    lua = '-- Generated by tools/build_native_lane_pilot.py; default-OFF Tools only.\n'
    lua += 'local M=' + lua_text(values) + '\nM.by_id={}\n'
    lua += 'for _,row in ipairs(M.rows) do M.by_id[row.archetype_id]=row end\nreturn M\n'
    bom = b'\xef\xbb\xbf' if original.startswith(b'\xef\xbb\xbf') else b''
    combined = prefix + original[len(bom):]
    return {OUTPUTS[0]: text.encode(), OUTPUTS[1]: lua.encode(),
            'scripts/npc/npc_units_custom.txt': combined}, original


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    outputs, original = build()
    if args.write:
        # The caller must preserve the complete dirty source before touching it.
        backup = ROOT / 'output/native_lane_pilot_20261013/pre_change/npc_units_custom.txt'
        assert backup.exists() and backup.read_bytes() == original, 'full pre-change backup required'
        for relative, data in outputs.items():
            path = ROOT / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_bytes() != data:
                path.write_bytes(data)
    else:
        for relative, data in outputs.items():
            assert (ROOT / relative).read_bytes() == data, 'generated file differs: ' + relative
    assert without_include((ROOT / 'scripts/npc/npc_units_custom.txt').read_bytes())[0] == original
    print('NATIVE_LANE_ALIASES_PASS 2 exact source copies; only BaseClass changed; original NPC bytes preserved')


if __name__ == '__main__':
    main()
