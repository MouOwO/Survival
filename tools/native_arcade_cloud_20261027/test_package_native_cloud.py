"""Temporary real signatures and VPKs; never builds a production candidate."""
from __future__ import annotations

import copy
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import sys
import unittest
from unittest.mock import patch

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


tool = load("native_cloud_package_under_test", HERE / "package_native_cloud.py")
fixtures = load("native_cloud_stream_fixtures", HERE.parent / "test_stream_workshop_vpk.py")
layout = load("native_cloud_layout_fixtures", HERE / "test_native_cloud_publish_layout.py")
REAL_ROOT = tool.ROOT
PROTECTED_RULE = "scripts/vscripts/config/generated/multiplayer_rules.lua"


class NativeCloudPackageTests(unittest.TestCase):
    def patched(self, target, name, value):
        context = patch.object(target, name, value)
        context.start()
        self.addCleanup(context.stop)

    def setUp(self):
        self.fixture = fixtures.StreamingVPKTests()
        self.fixture.setUp()
        self.addCleanup(self.fixture.doCleanups)
        f = self.fixture
        # A real, fixed 180-module inventory with opaque temporary protected
        # bytes. Production protected modules are neither copied nor rebuilt.
        policy = json.loads(tool.PROTECTION_POLICY.read_bytes())
        self.protected = set(policy["business_modules"])
        self.protected.add(PROTECTED_RULE)
        self.protected.update(policy["generated_prefix"] + "fixture_%03d.lua" % n for n in range(175))
        self.assertEqual(len(self.protected), 180)
        for name in sorted(self.protected):
            f.write(name, ("opaque protected fixture " + name).encode())
        for name in tool.pack.handoff.ENTRY_GATE_FILES:
            f.write(name, (REAL_ROOT / name).read_bytes())
        f.write(tool.pack.handoff.ACCESS_FILE, ('return {enabled=true,allowed_steamids={' +
            ','.join(json.dumps(sid) for sid in tool.pack.handoff.NATIVE_CLOUD_TESTERS) + '}}').encode())
        f.write("panorama/styles/custom_game/commerce_wallet.vcss_c", b"retired wallet fixture")
        # Match the canonical public-policy filenames without changing the
        # real production policy or keys. All test keypairs are generated by
        # the existing isolated Ed25519 fixture.
        integrity = json.loads((f.source / "policy.json").read_bytes())
        integrity["integrity"]["trusted_public_key"] = tool.POLICY_NAMES[1]
        (f.source / "policy.json").write_text(json.dumps(integrity), encoding="utf8")
        for name, raw in ((tool.POLICY_NAMES[0], json.dumps(integrity).encode()),
                          (tool.POLICY_NAMES[1], (f.source / "public.pem").read_bytes())):
            target = f.source / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(raw)
        f.seal()
        initial = f.build_split()
        self.base_vpk, self.before = Path(initial["output"]), copy.deepcopy(f.manifest)
        self.overlay, self.trusted, self.view, self.output = [f.base / name for name in ("thin", "new-trusted", "view", "new-vpk")]
        self.overlay.mkdir()
        self.trusted.mkdir()
        self.report = f.base / "final-plan.json"
        self.base_package = tool.pack.package_inventory(self.base_vpk)
        for name, value in dict(ROOT=f.source, BASE=f.candidate, BASE_TRUSTED=f.source, BASE_VPK=self.base_vpk,
                BASE_CONTENT=self.before["content_sha256"], BASE_SEQUENCE=10, BASE_COUNT=self.before["file_count"],
                BASE_PACKAGE=self.base_package, OVERLAY=self.overlay, TRUSTED=self.trusted, VIEW=self.view,
                OUTPUT=self.output, REPORT=self.report, ITEM="123456789").items():
            self.patched(tool, name, value)
        self.patched(tool.incremental, "ITEM", "123456789")
        for name in ("CONTENT", "COUNT", "ADDED_COUNT", "UPDATED_COUNT", "REPORT_SHA"):
            self.patched(tool, name, getattr(tool, name))
        pins = dict(tool.pack.handoff.NATIVE_CLOUD_ENTRY_PINS)
        pins[PROTECTED_RULE] = tool.pack.runtime.digest(f.candidate / PROTECTED_RULE)
        self.patched(tool.pack.handoff, "NATIVE_CLOUD_ENTRY_PINS", pins)
        self.replacements = {
            "addoninfo.txt": layout.INFO,
            "maps/ws4_entry.vpk": b"entry map fixture",
            "scripts/vscripts/addon_game_mode.lua": layout.MAIN,
            "scripts/vscripts/addon_game_mode_client.lua": tool.pack.handoff.NATIVE_CLOUD_INERT_CLIENT,
            "scripts/vscripts/systems/native_cloud_handoff.lua": (REAL_ROOT / "scripts/vscripts/systems/native_cloud_handoff.lua").read_bytes(),
            "scripts/vscripts/systems/native_cloud_roster.lua": (REAL_ROOT / "scripts/vscripts/systems/native_cloud_roster.lua").read_bytes(),
            tool.pack.runtime.RELEASE_PROFILE: b'return {channel="production",native_cloud_roster_required=true}',
            layout.WEB: b'return {enabled=true,base_url="https://pay.xiaofengnet.com/ws4-web"}',
            layout.SESSION: b'return {enabled=false,expected_map="template_map"}',
            layout.CASH: b'return {enabled=true,connection_helper=false,expected_map="template_map",base_url="https://pay.xiaofengnet.com/ws4-web"}',
        }
        self.reseal()

    def reseal(self, *, sequence=2026102708):
        for file in sorted(self.overlay.rglob("*"), reverse=True):
            if file.is_file(): file.unlink()
            elif file.is_dir(): file.rmdir()
        before = {row["path"]: row for row in self.before["files"]}
        after = {name: row for name, row in before.items() if name not in tool.REMOVED}
        for name, raw in self.replacements.items():
            path = self.overlay / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(raw)
            after[name] = dict(path=name, bytes=len(raw), md5=hashlib.md5(raw, usedforsecurity=False).hexdigest(),
                               sha256=hashlib.sha256(raw).hexdigest())
        self.after = copy.deepcopy(self.before)
        self.after.update(files=[after[name] for name in sorted(after)], file_count=len(after),
                          bytes=sum(row["bytes"] for row in after.values()))
        self.after["content_sha256"] = hashlib.sha256(tool.pack.runtime.manifest_payload(self.after)).hexdigest()
        (self.overlay / tool.pack.handoff.MANIFEST).write_text(json.dumps(self.after), encoding="utf8")
        tool.pack.protect_data.sign_manifest(self.overlay / tool.pack.handoff.MANIFEST, self.fixture.private,
                                            self.overlay / tool.pack.handoff.SIGNATURE, sequence)
        for name in tool.TRUST_NAMES:
            target = self.trusted / name
            target.parent.mkdir(parents=True, exist_ok=True)
            source = self.overlay / name if name in self.replacements else self.fixture.source / name if name in tool.POLICY_NAMES else self.fixture.candidate / name
            target.write_bytes(source.read_bytes())
        changes = [dict(path=name, before=before.get(name), after=after.get(name)) for name in sorted(
            {name for name in after if before.get(name) != after[name]} | tool.REMOVED)]
        added = sorted(set(after) - before.keys())
        for name, value in dict(CONTENT=self.after["content_sha256"], COUNT=len(after),
                ADDED_COUNT=len(added), UPDATED_COUNT=len(changes)-len(tool.REMOVED)).items():
            setattr(tool, name, value)
        report = dict(ok=True, status="READ_ONLY_PLAN", revision="WS4-NATIVE-CLOUD-02", release_sequence=tool.SEQUENCE,
            base_content_sha256=tool.BASE_CONTENT, base_files=tool.BASE_COUNT, projected_content_sha256=tool.CONTENT,
            expected_files=tool.COUNT, destination=str(self.overlay), trusted_source=str(self.trusted),
            view=str(self.view), package=str(self.output), protected_modules_preserved=180, protected_modules_rebuilt=0,
            four_accounts_preserved=True, production_preserved=True, online_cheats_allowed=False,
            web_auth=True, session_only=False, cash_code_enabled=True, connection_helper=False,
            full_view_canonical_required=True, default_map="ws4_entry", entry_capacity=4, gameplay_map="template_map", gameplay_capacity=4,
            native_cloud_roster_required=True,development_release_profile_modified=False,
            native_entry_handoff_acceptance="NOT_RUN", multiplayer_cloud_auth_acceptance="NOT_RUN",
            this_candidate_payment_acceptance="NOT_RUN", workshop_upload_performed=False, alias_installed=False,
            game_started=False, real_order_created=False, private_key_copied=False, changed=changes,
            allowed_additions=added, allowed_removals=sorted(tool.REMOVED),
            patch_sha256={name: after[name]["sha256"] for name in sorted(self.replacements)})
        self.report.write_text(json.dumps(report), encoding="utf8")
        tool.REPORT_SHA = tool.pack.runtime.digest(self.report)

    def assert_base_intact(self):
        self.assertEqual(tool.pack.package_inventory(self.base_vpk), self.base_package)
        self.assertTrue(tool.pack.runtime.verify(self.fixture.candidate, self.before)["ok"])

    def test_default_verifies_real_signatures_protection_and_hashes_without_creating_view(self):
        result = tool.run()
        self.assertTrue(result["signature_valid"])
        self.assertEqual(result["protected_modules_preserved"], 180)
        self.assertTrue(result["full_view_canonical_guard"].startswith("NOT_RUN"))
        self.assertEqual(result["deleted_runtime_paths"], sorted(tool.REMOVED))
        self.assertFalse(self.view.exists())
        self.assertFalse(self.output.exists())
        self.assert_base_intact()

    def test_real_roundtrip_runs_canonical_entry4_gate_and_never_writes_hardlinked_base(self):
        result = tool.run(build=True)
        self.assertEqual(result["full_view_canonical_guard"], "PASS")
        self.assertTrue(result["verification"]["manifest_dual_hashes_verified"])
        self.assertEqual(result["package_files"], tool.pack.package_inventory(Path(result["output"])))
        self.assertFalse((self.view / next(iter(tool.REMOVED))).exists())
        for row in self.after["files"]:
            if row["path"] in self.replacements:
                self.assertFalse(os.path.samefile(self.view / row["path"], self.overlay / row["path"]))
            else:
                self.assertTrue(os.path.samefile(self.view / row["path"], self.fixture.candidate / row["path"]))
        for index in result["reused_archives"]:
            self.assertTrue(os.path.samefile(self.output / f"123456789_{index:03}.vpk", self.base_vpk.with_name(f"123456789_{index:03}.vpk")))
        self.assert_base_intact()

    def test_modified_or_extra_overlay_and_wrong_signature_fail_without_outputs(self):
        target = self.overlay / "addoninfo.txt"
        target.write_bytes(target.read_bytes() + b"tampered")
        with self.assertRaisesRegex(ValueError, "hash mismatch"): tool.run(build=True)
        self.reseal()
        (self.overlay / "foreign.txt").write_bytes(b"foreign")
        with self.assertRaisesRegex(ValueError, "exactly changed"): tool.run(build=True)
        self.reseal(sequence=2026102707)
        with self.assertRaisesRegex(ValueError, "sequence/content/count"): tool.run(build=True)
        self.assertFalse(self.view.exists())
        self.assertFalse(self.output.exists())

    def test_protected_module_changed_with_valid_signature_and_reviewed_plan_is_rejected(self):
        self.replacements[PROTECTED_RULE] = b"changed opaque protected fixture"
        self.reseal()
        with self.assertRaisesRegex(ValueError, "Protected 180-module"): tool.run(build=True)
        self.assertFalse(self.view.exists())
        self.assert_base_intact()

    def test_canonical_rejects_signed_bare_client_before_any_vpk_write(self):
        self.replacements["scripts/vscripts/addon_game_mode_client.lua"] = b'SendToConsole("dota_launch_custom_game 3824360109 template_map")'
        self.reseal()
        with self.assertRaisesRegex(ValueError, "inert source"): tool.run(build=True)
        self.assertFalse(self.view.exists())
        self.assertFalse(self.output.exists())
        self.assert_base_intact()

    def test_receipt_scope_and_trusted_policy_are_not_trusted_from_candidate(self):
        self.report.write_bytes(self.report.read_bytes() + b"\n")
        with self.assertRaisesRegex(ValueError, "plan receipt differs"): tool.run(build=True)
        self.reseal()
        d = json.loads(self.report.read_bytes()); d["changed"] = d["changed"][:-1]
        self.report.write_text(json.dumps(d), encoding="utf8"); tool.REPORT_SHA = tool.pack.runtime.digest(self.report)
        with self.assertRaisesRegex(ValueError, "inventory differs from final reviewed plan"): tool.run(build=True)
        self.reseal()
        target = self.trusted / tool.POLICY_NAMES[0]
        target.write_bytes(target.read_bytes() + b"\n")
        with self.assertRaisesRegex(ValueError, "policy/public key differs"): tool.run(build=True)
        self.assertFalse(self.view.exists())

    def test_materialization_failure_cleans_only_owned_view_and_keeps_base(self):
        original = tool.incremental.copy_new
        def fail(source, destination, row):
            original(source, destination, row)
            raise ValueError("injected exclusive-copy failure")
        with patch.object(tool.incremental, "copy_new", side_effect=fail):
            with self.assertRaisesRegex(ValueError, "exclusive-copy failure"): tool.run(build=True)
        self.assertFalse(self.view.exists())
        self.assertFalse(self.output.exists())
        self.assert_base_intact()

    def test_cli_has_no_path_sequence_or_signing_override(self):
        for args in (["--sequence", "2026102705"], ["--overlay", "elsewhere"], ["--key", "secret.pem"]):
            with self.assertRaises(SystemExit): tool.parser().parse_args(args)
        occupied = self.output
        occupied.mkdir(); (occupied / "keep.txt").write_bytes(b"user data")
        with self.assertRaisesRegex(ValueError, "empty"): tool.run(build=True)
        self.assertEqual((occupied / "keep.txt").read_bytes(), b"user data")


if __name__ == "__main__":
    unittest.main()
